"""Per-browser storage paths for the public demo deployment.

The workspace ID is generated by Flask and stored in its signed session cookie.
A ContextVar keeps concurrent Gunicorn threads isolated.
"""
from contextvars import ContextVar, Token
import os
from typing import Optional

_workspace_id: ContextVar[Optional[str]] = ContextVar("app_workspace_id", default=None)


def set_workspace_id(value: str) -> Token:
    if not isinstance(value, str) or len(value) != 48 or any(c not in "0123456789abcdef" for c in value):
        raise ValueError("Invalid workspace identifier")
    return _workspace_id.set(value)


def reset_workspace_id(token: Token) -> None:
    _workspace_id.reset(token)


def get_workspace_id() -> Optional[str]:
    return _workspace_id.get()


def workspace_root() -> str:
    workspace_id = get_workspace_id()
    if not workspace_id:
        return os.path.abspath(os.environ.get("APP_DATA_ROOT", "data"))
    return os.path.abspath(os.path.join(
        os.environ.get("APP_DATA_ROOT", "data"), "workspaces", workspace_id
    ))


def workspace_path(relative_path: str, default_path: Optional[str] = None) -> str:
    workspace_id = get_workspace_id()
    if not workspace_id:
        return default_path if default_path is not None else os.path.abspath(relative_path)

    root = workspace_root()
    target = os.path.abspath(os.path.join(root, relative_path))
    if os.path.commonpath([root, target]) != root:
        raise ValueError("Workspace path escapes its storage directory")
    return target
